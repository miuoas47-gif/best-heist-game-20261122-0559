// Velvet Vault — a tiny static server for play-testing game/ locally.
// Serves this directory's game/ folder at http://localhost:8080 with no other
// behaviour; the game itself makes no network requests once loaded.
//
//   node serve.ts

import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('./game/', import.meta.url));
const PORT = 8080;

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
};

const server = createServer(async (req, res) => {
  try {
    const path = req.url === '/' || !req.url ? 'index.html' : decodeURIComponent(req.url.split('?')[0].replace(/^\/+/, ''));
    if (path.includes('..')) throw new Error('bad path');
    const body = await readFile(join(root, path));
    res.writeHead(200, { 'content-type': TYPES[extname(path)] ?? 'application/octet-stream' });
    res.end(body);
  } catch {
    res.writeHead(404, { 'content-type': 'text/plain' });
    res.end('not found');
  }
});

server.listen(PORT, '127.0.0.1', () => {
  console.log(`Velvet Vault at http://localhost:${PORT}`);
});
